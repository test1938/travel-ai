package dev.travelpilot.recommendation;

import static org.assertj.core.api.Assertions.assertThat;

import dev.travelpilot.common.domain.Destination;
import dev.travelpilot.integration.weather.Forecast;
import dev.travelpilot.support.Personas;
import dev.travelpilot.support.TestProps;
import dev.travelpilot.trip.TripRequest;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import org.junit.jupiter.api.Test;

/**
 * Approval test: the activity candidates per persona are written to src/test/resources/snapshots/candidates.md and must not
 * change silently. After an intended scoring change, delete the file, run the test, review the diff and commit.
 */
class PersonaSnapshotTest {

    static final Path SNAPSHOT = Path.of("src", "test", "resources", "snapshots", "candidates.md");
    private final CandidateSelector selector = new CandidateSelector(TestProps.defaults().scoring().weights());

    /** Activity candidates the planner will see, best score first (at most days x 4, min 8, + preference picks). */
    private List<ScoredPlace> candidates(TripRequest req) {
        return selector.select(Personas.CATALOG, req, Forecast.NONE, HardFilter.Options.defaults()).activities();
    }

    private static TripRequest inDanang(TripRequest r) {
        return new TripRequest(Destination.DANANG, r.startDate(), r.days(), r.adults(), r.childrenAges(),
                r.budgetVnd(), r.preferences(), r.pace(), r.notes());
    }

    @Test
    void familyGetsBaNaHills() {
        assertThat(candidates(Personas.family())).extracting(ScoredPlace::id).contains(Personas.BA_NA);
    }

    @Test
    void differentTravelersInTheSameCityGetDifferentRankings() {
        List<String> family = ids(candidates(Personas.family()));
        List<String> couple = ids(candidates(inDanang(Personas.couple())));
        List<String> friends = ids(candidates(inDanang(Personas.friends())));

        assertThat(family).isNotEqualTo(couple).isNotEqualTo(friends);
        assertThat(couple).isNotEqualTo(friends);
    }

    @Test
    void snapshotMatches() throws IOException {
        Map<String, TripRequest> personas = new LinkedHashMap<>();
        personas.put("1 family / DANANG", Personas.family());
        personas.put("2 couple / HANOI", Personas.couple());
        personas.put("3 friends / QUANGNINH", Personas.friends());
        personas.put("2' couple / DANANG", inDanang(Personas.couple()));
        personas.put("3' friends / DANANG", inDanang(Personas.friends()));

        StringBuilder md = new StringBuilder("# Activity candidates per persona (generated by PersonaSnapshotTest)\n");
        personas.forEach((name, req) -> {
            md.append("\n## ").append(name).append("\n\n| # | id | name | total | pref | budget | dist | sched | group | pop |\n")
                    .append("|---|---|---|---|---|---|---|---|---|---|\n");
            List<ScoredPlace> top = candidates(req);
            for (int i = 0; i < top.size(); i++) {
                ScoredPlace s = top.get(i);
                ScoreBreakdown b = s.score();
                md.append(String.format(Locale.ROOT, "| %d | %s | %s | %.3f | %.2f | %.2f | %.2f | %.2f | %.2f | %.2f |%n",
                        i + 1, s.id(), s.place().name(), b.total(), b.preference(), b.budget(), b.distance(),
                        b.schedule(), b.group(), b.popularity()));
            }
        });
        String actual = md.toString().replace("\r\n", "\n");

        if (!Files.exists(SNAPSHOT)) {
            Files.createDirectories(SNAPSHOT.getParent());
            Files.writeString(SNAPSHOT, actual, StandardCharsets.UTF_8);
        }
        assertThat(actual).isEqualTo(Files.readString(SNAPSHOT, StandardCharsets.UTF_8).replace("\r\n", "\n"));
    }

    private static List<String> ids(List<ScoredPlace> places) {
        return places.stream().map(ScoredPlace::id).toList();
    }
}
